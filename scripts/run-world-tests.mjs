import {createRequire} from 'node:module';
import {dirname,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const wranglerRoot=dirname(require.resolve('wrangler/package.json'));
const {build}=await import(pathToFileURL(require.resolve('esbuild',{paths:[wranglerRoot]})).href);
const output=resolve('.sites-runtime/worlds.test.mjs');
await build({entryPoints:['tests/worlds.test.ts'],bundle:true,platform:'node',format:'esm',packages:'external',jsx:'automatic',outfile:output});
const result=spawnSync(process.execPath,['--test',output],{stdio:'inherit'});
process.exitCode=result.status??1;
