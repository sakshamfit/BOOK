import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import tailwind from "@tailwindcss/postcss";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
// PostCSS is already a dependency of the project's Tailwind plugin.
const postcss = createRequire(import.meta.resolve("@tailwindcss/postcss"))("postcss");
const input = resolve(here, "clothing-rail.input.css");
const result = await postcss([tailwind({ base: here, optimize: { minify: true } })])
  .process(await readFile(input, "utf8"), { from: input });

// The preview is not a Tailwind app. Scope utility selectors to the rail AND
// its portalled detail view, and flatten layers in cascade order so legacy
// unlayered button rules cannot override the supplied component's utilities.
const layers = new Map();
result.root.walkAtRules("layer", (layer) => {
  if (!layer.nodes) { layer.remove(); return; }
  if (layer.params === "theme") {
    layer.walkRules((rule) => { if (rule.selector === ":root, :host" || rule.selector === ":root,:host") rule.selector = "[data-orion-rail]"; });
  }
  if (layer.params === "utilities") {
    layer.walkRules((rule) => {
      let parent = rule.parent;
      while (parent && parent !== layer) {
        if (parent.type === "rule" || (parent.type === "atrule" && parent.name.endsWith("keyframes"))) return;
        parent = parent.parent;
      }
      rule.selectors = rule.selectors.flatMap((selector) => [
        `:where([data-orion-rail])${selector}`,
        `:where([data-orion-rail]) ${selector}`,
      ]);
    });
  }
  // Tailwind's generated property defaults must not reset other page widgets.
  if (layer.params === "properties") layer.walkRules((rule) => {
    rule.selector = ":where([data-orion-rail], [data-orion-rail] *, [data-orion-rail] *::before, [data-orion-rail] *::after)";
  });
  const bucket = layers.get(layer.params) ?? [];
  bucket.push(...layer.nodes.map((node) => node.clone()));
  layers.set(layer.params, bucket);
  layer.remove();
});
const css = postcss.root();
for (const name of ["properties", "theme", "base", "components", "utilities"]) {
  css.append(layers.get(name) ?? []);
  layers.delete(name);
}
if (layers.size) throw new Error(`Unexpected Tailwind layer: ${[...layers.keys()].join(", ")}`);
css.append(result.root.nodes);
await writeFile(resolve(here, "clothing-rail.css"), `/* Generated by build-clothing-rail.mjs; edit clothing-rail.input.css instead. */\n${css.toString()}\n`);

await build({
  absWorkingDir: here,
  entryPoints: ["clothing-rail-entry.tsx"],
  outfile: "clothing-rail.js",
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  // Both the app and the static preview have React installed. Resolve all
  // components (including Lucide) to ONE copy to avoid invalid-hook errors.
  alias: {
    react: dirname(require.resolve("react/package.json")),
    "react-dom": dirname(require.resolve("react-dom/package.json")),
  },
});
console.log("Built Orion clothing rail: clothing-rail.css + clothing-rail.js");
